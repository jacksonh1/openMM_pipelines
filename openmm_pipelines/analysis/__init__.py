def analyze(outdir, config: AnalysisConfig | None = None) -> Path:
    """Default-overview analysis of a completed plain-MD run: drift (RMSD to design), Rg,
    per-residue RMSF, secondary structure, conformational clusters, and — for a complex —
    interchain metrics. Writes `outdir/analysis/`."""
    outdir = Path(outdir)
    config = config or AnalysisConfig()
    layout = RunLayout(outdir, read_storage_directory(outdir))
    adir = outdir / "analysis"
    adir.mkdir(parents=True, exist_ok=True)

    try:
        export_processed_trajectory(outdir)  # viewable processed.xtc + processed_topology.pdb

        protein = to_protein(load_system_trajectory(outdir))  # imaged, protein-only, NOT superposed
        reference = load_input_reference(outdir)
        time_ps = protein.time

        # Interchain metrics first: they are minimum-image-based and need coordinates + box in
        # the same (lab) frame, so they must run BEFORE superposition rotates the coordinates.
        npz = {"time_ps": time_ps}
        summary = {"n_frames": int(protein.n_frames),
                   "n_residues": int(protein.topology.n_residues)}
        chains = protein_chain_ids(protein)
        if len(chains) >= 2 and config.interchain:
            inter_summary, inter_arrays = interchain_report(
                protein, reference, adir, time_ps, "time (ps)", config
            )
            summary["interchain"] = inter_summary
            npz.update(inter_arrays)

        # Drift + clustering need frames superposed onto the design pose.
        superpose_to_reference(protein, reference)
        drift, arrays = drift_report(protein, reference, adir, time_ps, "time (ps)",
                                     "drift from input pose")
        cluster = cluster_and_report(protein, reference, config, adir, time_ps, "time (ps)")

        summary.update(drift)
        summary["clustering"] = cluster_summary(cluster)
        summary["analysis_config"] = config.model_dump(mode="json")
        npz.update(arrays)
        npz["cluster_labels"] = cluster.labels
        npz["cluster_frame_indices"] = cluster.frame_indices

        np.savez(adir / "analysis_data.npz", **npz)
        write_json(summary, adir / "analysis_report.json")
        if config.html_report:
            write_html_report(adir, summary, npz, "time_ps", "time (ps)", outdir.name)
    finally:
        layout.mirror("analysis")  # copy the overview into storage (storage = full record)
    return adir
